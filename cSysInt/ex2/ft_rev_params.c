#include <unistd.h>

int	main(int ac, char **av)
{
	int	i;
	int	c;

	i = 0;
	c = ac - 1;
	(void)ac;
	while (c > 0)
	{
		i = 0;
		while (av[c][i])
		{
			write(1, &av[c][i], 1);
			i++;
		}
		write(1, "\n", 1);
		c--;
	}
}
